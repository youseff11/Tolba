"""Zone / line rules: validation, storage API and export to the AI server's YAML format.

Format (see HOW_TO_USE_AR.md §4.4 and configs/zones.example.yaml of the AI package):

CAM-01:
  zones:
    - name: entrance
      polygon: [[0.15, 0.55], [0.85, 0.55], [0.9, 0.95], [0.1, 0.95]]
      classes: [person]
      loiter_sec: 15
      crowd_count: 4
      crowd_sec: 5
  lines:
    - name: gate
      p1: [0.5, 0.15]
      p2: [0.5, 0.55]
      a_label: west
      b_label: east

Coordinates are normalised: x 0 (left) → 1 (right), y 0 (top) → 1 (bottom).
"""
import json
import re

from django.http import HttpResponse
from rest_framework import status
from rest_framework.exceptions import ValidationError
from rest_framework.response import Response
from rest_framework.views import APIView

from .models import CameraZones

CLASSES = {"person", "car", "motorcycle", "bus", "truck", "bicycle"}
CAMERA_RE = re.compile(r"^CAM-\d{2,}$")


def _point(p, where):
    if not (isinstance(p, (list, tuple)) and len(p) == 2):
        raise ValidationError({where: "Each point must be [x, y]"})
    x, y = (float(v) for v in p)
    if not (0 <= x <= 1 and 0 <= y <= 1):
        raise ValidationError({where: "Coordinates must be between 0 and 1"})
    return [round(x, 4), round(y, 4)]


def _pos_number(v, where, integer=False):
    if v in (None, ""):
        return None
    try:
        n = int(v) if integer else float(v)
    except (TypeError, ValueError):
        raise ValidationError({where: "Must be a number"})
    if n <= 0:
        raise ValidationError({where: "Must be greater than 0"})
    return n


def clean(data):
    zones, lines, names = [], [], set()
    for i, z in enumerate(data.get("zones") or []):
        name = str(z.get("name") or "").strip()
        if not name:
            raise ValidationError({f"zones[{i}].name": "Name is required"})
        if name in names:
            raise ValidationError({f"zones[{i}].name": f"Duplicate name '{name}'"})
        names.add(name)
        poly = [_point(p, f"zones[{i}].polygon") for p in z.get("polygon") or []]
        if len(poly) < 3:
            raise ValidationError({f"zones[{i}].polygon": "A zone needs at least 3 points"})
        classes = [c for c in z.get("classes") or [] if c in CLASSES] or ["person"]
        out = {"name": name, "polygon": poly, "classes": classes}
        for key, integer in (("loiter_sec", False), ("crowd_count", True), ("crowd_sec", False)):
            n = _pos_number(z.get(key), f"zones[{i}].{key}", integer)
            if n is not None:
                out[key] = n
        if ("crowd_count" in out) != ("crowd_sec" in out):
            raise ValidationError({f"zones[{i}]": "Crowding needs both crowd_count and crowd_sec"})
        zones.append(out)
    for i, ln in enumerate(data.get("lines") or []):
        name = str(ln.get("name") or "").strip()
        if not name:
            raise ValidationError({f"lines[{i}].name": "Name is required"})
        if name in names:
            raise ValidationError({f"lines[{i}].name": f"Duplicate name '{name}'"})
        names.add(name)
        p1, p2 = _point(ln.get("p1"), f"lines[{i}].p1"), _point(ln.get("p2"), f"lines[{i}].p2")
        if p1 == p2:
            raise ValidationError({f"lines[{i}]": "The two points of a line must differ"})
        lines.append({
            "name": name, "p1": p1, "p2": p2,
            "a_label": str(ln.get("a_label") or "A").strip(), "b_label": str(ln.get("b_label") or "B").strip(),
        })
    return zones, lines


# ---------------------------------------------------------------- YAML export (no PyYAML needed)

def _q(s):
    return json.dumps(s, ensure_ascii=False)  # a JSON string is a valid YAML double-quoted scalar


def _n(x):
    return f"{x:.4f}".rstrip("0").rstrip(".") if isinstance(x, float) else str(x)


def _pt(p):
    return f"[{_n(p[0])}, {_n(p[1])}]"


def to_yaml(configs):
    out = ["# VisionSeek zones & lines – generated by the VisionSeek web platform", "# x: 0 = left, 1 = right · y: 0 = top, 1 = bottom", ""]
    for cfg in configs:
        if not cfg.zones and not cfg.lines:
            continue
        out.append(f"{cfg.camera_code}:")
        if cfg.zones:
            out.append("  zones:")
            for z in cfg.zones:
                out.append(f"    - name: {_q(z['name'])}")
                out.append(f"      polygon: [{', '.join(_pt(p) for p in z['polygon'])}]")
                out.append(f"      classes: [{', '.join(z['classes'])}]")
                for key in ("loiter_sec", "crowd_count", "crowd_sec"):
                    if key in z:
                        out.append(f"      {key}: {_n(z[key])}")
        if cfg.lines:
            out.append("  lines:")
            for ln in cfg.lines:
                out.append(f"    - name: {_q(ln['name'])}")
                out.append(f"      p1: {_pt(ln['p1'])}")
                out.append(f"      p2: {_pt(ln['p2'])}")
                out.append(f"      a_label: {_q(ln['a_label'])}")
                out.append(f"      b_label: {_q(ln['b_label'])}")
        out.append("")
    return "\n".join(out)


def _ser(cfg):
    return {
        "camera": cfg.camera_code, "zones": cfg.zones, "lines": cfg.lines,
        "updated_by": str(cfg.updated_by or ""), "updated_at": cfg.updated_at.isoformat() if cfg.updated_at else None,
    }


class ZonesListView(APIView):
    def get(self, request):
        return Response([_ser(c) for c in CameraZones.objects.all()])


class ZonesDetailView(APIView):
    def get(self, request, camera):
        cfg = CameraZones.objects.filter(camera_code=camera).first()
        return Response(_ser(cfg) if cfg else {"camera": camera, "zones": [], "lines": [], "updated_by": "", "updated_at": None})

    def put(self, request, camera):
        if not CAMERA_RE.match(camera):
            raise ValidationError({"camera": "Camera code must look like CAM-01"})
        zones, lines = clean(request.data)
        cfg, _ = CameraZones.objects.update_or_create(
            camera_code=camera, defaults={"zones": zones, "lines": lines, "updated_by": request.user}
        )
        return Response(_ser(cfg), status=status.HTTP_200_OK)


class ZonesExportView(APIView):
    def get(self, request):
        text = to_yaml(CameraZones.objects.all())
        resp = HttpResponse(text, content_type="text/yaml; charset=utf-8")
        resp["Content-Disposition"] = 'attachment; filename="my_zones.yaml"'
        return resp
